const assert = require("node:assert/strict")
const M = require("../Model.js")
const days = ["2026-10-26", "2026-10-27", "2026-10-28", "2026-10-29", "2026-10-30"]
assert.deepEqual(M.creationSlot(days, 150, 60, 100, 40, 7), {day:"2026-10-27",minutes:510})
assert.deepEqual(M.creationSlot(days, 50, 17, 100, 40, 7), {day:"2026-10-26",minutes:435})
assert.deepEqual(M.creationSlot(days, 50, 120, 100, 40, 7), {day:"2026-10-26",minutes:600})
assert.deepEqual(M.creationSlot([days[0]], 50, 960, 100, 40, 0), {day:days[0],minutes:1425})
for (const args of [
  [days,-1,0,100,40,7], [days,500,0,100,40,7], [days,0,-1,100,40,7],
  [days,0,0,0,40,7], [days,0,0,100,0,7], [[],0,0,100,40,7],
  [days,NaN,0,100,40,7], [days,0,0,100,40,NaN]
]) assert.equal(M.creationSlot(...args), null)
const now = new Date(2026,9,28,12,5)
const selected = M.newDraft("2026-10-31", now, "School/calendar", 14*60+15)
assert.equal(selected.date,"2026-10-31")
assert.equal(selected.from,"14:15")
assert.equal(selected.to,"15:15")
assert.equal(selected.endDate,"2026-10-31")
const midnight = M.newDraft("2026-10-31", now, "School/calendar", 0)
assert.equal(midnight.from,"00:00")
assert.equal(midnight.to,"01:00")
const late = M.newDraft("2026-10-31", now, "School/calendar", 23*60+45)
assert.equal(late.from,"23:45")
assert.equal(late.to,"00:45")
assert.equal(late.endDate,"2026-11-01")
const moved = M.moveCreationDate({...late,title:"Keep",location:"Room",allDay:false},"2026-11-01")
assert.equal(moved.date,"2026-11-01")
assert.equal(moved.endDate,"2026-11-02")
assert.equal(moved.from,"23:45")
assert.equal(moved.to,"00:45")
assert.equal(moved.title,"Keep")
assert.equal(moved.location,"Room")
const multi = M.moveCreationDate({...selected,date:"2026-10-31",endDate:"2026-11-03"},"2026-11-05")
assert.equal(multi.endDate,"2026-11-08")
assert.equal(late.date,"2026-10-31")
assert.equal(M.newDraft("2026-10-31",now,"School/calendar",-1).from,"09:00")
console.log("Creation targeting passed: day/column, quarter-hour snapping, scroll-content coordinates, midnight, overnight/DST dates, and retained draft fields")
